def load_camera_metrics(metrics_path: str) -> Dict[str, Any]:
    """Loads camera calibration and motion metrics JSON generated by camera_motion.py."""
    if not os.path.isfile(metrics_path):
        raise FileNotFoundError(f"Camera metrics file not found: {metrics_path}")
    with open(metrics_path, "r") as f:
        return json.load(f)


def find_striker_box(
    boxes: np.ndarray,
    confs: np.ndarray,
    frame_idx: int,
    prev_box: Optional[np.ndarray] = None
) -> int:
    """
    Identifies Liam Livingstone (the striker) among detected persons across frames 22-71.
    Rules:
    - Pitch corridor: Striker is horizontally centered near pitch center (abs(cx - 380) <= 130).
    - Vertical range: 260.0 <= cy <= 750.0 across all active shot frames.
    - Continuity: If prev_box is available, penalize distance smoothly without artificial frame splits.
    """
    best_idx = -1
    best_score = -1e9

    for i, (b, conf) in enumerate(zip(boxes, confs)):
        if conf < 0.2:
            continue
        cx = (b[0] + b[2]) / 2.0
        cy = (b[1] + b[3]) / 2.0

        # Pitch corridor check
        x_dist = abs(cx - 380.0)
        if x_dist > 130.0:
            continue

        # Active striker vertical tracking bounds
        if not (260.0 <= cy <= 750.0):
            continue

        score = conf * 10.0 - x_dist * 0.1

        # Smooth distance continuity from previous tracked box
        if prev_box is not None:
            prev_cx = (prev_box[0] + prev_box[2]) / 2.0
            prev_cy = (prev_box[1] + prev_box[3]) / 2.0
            dist_prev = np.sqrt((cx - prev_cx)**2 + (cy - prev_cy)**2)
            score -= dist_prev * 0.05

        if score > best_score:
            best_score = score
            best_idx = i

    return best_idx


def refine_bat_vector(
    image: np.ndarray,
    pivot: np.ndarray,
    u_prior: np.ndarray,
    bat_len_px: float,
    search_angle_deg: float = 65.0,
    is_stance: bool = False
) -> Tuple[np.ndarray, float]:
    """
    Refines the bat blade direction by combining the biomechanical forearm prior
    with an image gradient / intensity search along radial lines from the handle pivot.
    In stance, enforces angular continuity to avoid jumping to white batting pads.
    """
    h_img, w_img = image.shape[:2]
    prior_angle = np.arctan2(u_prior[1], u_prior[0])
    best_angle = prior_angle
    best_score = -1e9
    best_bright = 0.0

    # Angular search grid around forearm prior
    num_angles = 31
    angles = np.linspace(
        prior_angle - np.deg2rad(search_angle_deg),
        prior_angle + np.deg2rad(search_angle_deg),
        num_angles
    )
    # Radial sample points along bat length
    radii = np.linspace(16.0, bat_len_px, 16)

    for a in angles:
        deg = np.rad2deg(a) % 360
        # In stance, prevent jumping to vertical white pads (70 to 105 deg)
        if is_stance and 70.0 <= deg <= 105.0:
            continue

        u_cand = np.array([np.cos(a), np.sin(a)])
        brightness_vals = []
        valid = True
        for r in radii:
            pt = pivot + r * u_cand
            x, y = int(round(pt[0])), int(round(pt[1]))
            if 0 <= x < w_img and 0 <= y < h_img:
                bgr = image[y, x]
                bright = float(np.mean(bgr))
                brightness_vals.append(bright)
            else:
                valid = False
                break

        if valid and len(brightness_vals) > 0:
            avg_bright = np.mean(brightness_vals)
            # Angular deviation penalty from forearm prior
            angle_diff = abs(a - prior_angle)
            # Bat blade wood/sticker has high lightness compared to green pitch (~85)
            score = avg_bright - 35.0 * (angle_diff**2)
            if score > best_score:
                best_score = score
                best_angle = a
                best_bright = avg_bright

    u_refined = np.array([np.cos(best_angle), np.sin(best_angle)])
    return u_refined, best_bright


def compute_bat_confidence(
    image: np.ndarray,
    pivot: np.ndarray,
    sweet_spot: np.ndarray,
    pivot_conf: float,
    blade_brightness: float = 0.0
) -> float:
    """
    Measures bat visibility and edge/smear confidence along the bat blade axis.
    Uses Sobel gradient magnitude and color contrast between bat blade (wood/white)
    and grass background.
    """
    h_img, w_img = image.shape[:2]
    num_samples = 20
    t_vals = np.linspace(0.2, 1.1, num_samples)
    sampled_coords = [pivot + t * (sweet_spot - pivot) for t in t_vals]

    valid_coords = []
    for pt in sampled_coords:
        x, y = int(round(pt[0])), int(round(pt[1]))
        if 0 <= x < w_img and 0 <= y < h_img:
            valid_coords.append((x, y))

    if len(valid_coords) < 5:
        return float(np.clip(pivot_conf * 0.5, 0.0, 1.0))

    min_x = max(0, min(pt[0] for pt in valid_coords) - 15)
    max_x = min(w_img - 1, max(pt[0] for pt in valid_coords) + 15)
    min_y = max(0, min(pt[1] for pt in valid_coords) - 15)
    max_y = min(h_img - 1, max(pt[1] for pt in valid_coords) + 15)

    patch = image[min_y:max_y+1, min_x:max_x+1]
    if patch.size == 0:
        return float(np.clip(pivot_conf, 0.0, 1.0))

    gray_patch = cv2.cvtColor(patch, cv2.COLOR_BGR2GRAY)
    grad_x = cv2.Sobel(gray_patch, cv2.CV_32F, 1, 0, ksize=3)
    grad_y = cv2.Sobel(gray_patch, cv2.CV_32F, 0, 1, ksize=3)
    grad_mag = np.sqrt(grad_x**2 + grad_y**2)

    grad_energies = []
    brightness_vals = []
    for vx, vy in valid_coords:
        lx = vx - min_x
        ly = vy - min_y
        if 0 <= lx < grad_mag.shape[1] and 0 <= ly < grad_mag.shape[0]:
            grad_energies.append(grad_mag[ly, lx])
            brightness_vals.append(gray_patch[ly, lx])

    avg_grad = np.mean(grad_energies) if grad_energies else 0.0
    avg_bright = np.mean(brightness_vals) if brightness_vals else blade_brightness

    grad_score = np.clip(avg_grad / 40.0, 0.0, 1.0)
    bright_score = np.clip((avg_bright - 65.0) / 95.0, 0.0, 1.0)
    texture_conf = 0.5 * grad_score + 0.5 * bright_score

    combined_conf = 0.55 * pivot_conf + 0.45 * texture_conf
    return float(np.clip(combined_conf, 0.05, 0.98))


def classify_shot_phase(frame_idx: int) -> str:
    """Classifies temporal shot phase based on action sequence."""
    if frame_idx <= 21:
        return "Pre-Shot"
    elif 22 <= frame_idx <= 47:
        return "Stance"
    elif 48 <= frame_idx <= 54:
        return "Backlift"
    elif 55 <= frame_idx <= 56:
        return "Downswing"
    elif frame_idx == 57:
        return "Impact"
    else:
        return "Follow-Through"


def track_and_extract_kinematics(
    frames_dir: str,
    metrics_path: str,
    pose_model_path: str = "yolov8x-pose.pt"
) -> Tuple[pd.DataFrame, List[Dict[str, Any]]]:
    """
    Main tracking and kinematic trajectory pipeline.
    Processes all frames, extracts keypoints, compensates for camera motion,
    applies Savitzky-Golay filtering, classifies failure modes, and builds dataset.
    """
    camera_metrics = load_camera_metrics(metrics_path)
    fps = float(camera_metrics["video_info"]["fps"])
    m_per_px = float(camera_metrics["stump_calibration"]["meters_per_pixel"])
    bat_len_px = 0.60 / m_per_px  # 0.60 m bat blade sweet-spot distance (~83.7 px)
    frame_motions = camera_metrics["frame_motions"]
    total_frames = len(frame_motions)

    print(f"Loading YOLOv8 pose model: {pose_model_path}...")
    model = YOLO(pose_model_path)

    raw_records = []
    prev_striker_box = None

    print(f"Processing {total_frames} frames from {frames_dir}...")
    for f_idx in range(total_frames):
        frame_file = os.path.join(frames_dir, f"frame_{f_idx:04d}.png")
        if not os.path.isfile(frame_file):
            raise FileNotFoundError(f"Frame file missing: {frame_file}")

        motion = frame_motions[f_idx]
        dx_cam = float(motion["dx_cam"])
        dy_cam = float(motion["dy_cam"])
        v_cam = float(motion["v_cam_px_s"])
        timestamp = float(f_idx / fps)
        shot_phase = classify_shot_phase(f_idx)

        # Pre-shot scene (frames 0 to 21)
        if f_idx < 22:
            raw_records.append({
                "frame_idx": f_idx,
                "timestamp": timestamp,
                "shot_phase": shot_phase,
                "lw_x": 0.0, "lw_y": 0.0, "lw_conf": 0.0,
                "rw_x": 0.0, "rw_y": 0.0, "rw_conf": 0.0,
                "raw_pivot_x": 0.0, "raw_pivot_y": 0.0,
                "pivot_x": 0.0, "pivot_y": 0.0, "pivot_conf": 0.0,
                "inter_wrist_dist_px": 0.0,
                "bat_x": 0.0, "bat_y": 0.0, "bat_conf": 0.0,
                "ls_x": 0.0, "ls_y": 0.0, "ls_conf": 0.0,
                "rs_x": 0.0, "rs_y": 0.0, "rs_conf": 0.0,
                "le_x": 0.0, "le_y": 0.0, "le_conf": 0.0,
                "re_x": 0.0, "re_y": 0.0, "re_conf": 0.0,
                "dx_cam": dx_cam, "dy_cam": dy_cam, "v_cam_px_s": v_cam,
                "striker_box": None,
                "tracked": False
            })
            continue

        img = cv2.imread(frame_file)
        res = model(img, verbose=False)[0]

        boxes = res.boxes.xyxy.cpu().numpy()
        confs = res.boxes.conf.cpu().numpy()
        kpts = res.keypoints.data.cpu().numpy()

        striker_idx = find_striker_box(boxes, confs, f_idx, prev_striker_box)

        if striker_idx >= 0:
            b = boxes[striker_idx]
            prev_striker_box = b
            k = kpts[striker_idx]

            # COCO Keypoints:
            # 5: ls, 6: rs, 7: le, 8: re, 9: lw, 10: rw
            ls = k[5]
            rs = k[6]
            le = k[7]
            re = k[8]
            lw = k[9]
            rw = k[10]

            lw_x, lw_y, lw_conf = float(lw[0]), float(lw[1]), float(lw[2])
            rw_x, rw_y, rw_conf = float(rw[0]), float(rw[1]), float(rw[2])

            pivot_x = (lw_x + rw_x) / 2.0
            pivot_y = (lw_y + rw_y) / 2.0
            pivot_conf = min(lw_conf, rw_conf)

            d_wrist = float(np.sqrt((lw_x - rw_x)**2 + (lw_y - rw_y)**2))

            # Forearm-to-wrist bat proxy vector:
            mid_elbow = (le[:2] + re[:2]) / 2.0
            v_forearm = np.array([pivot_x, pivot_y]) - mid_elbow
            norm_v = np.linalg.norm(v_forearm)
            if norm_v > 1e-3:
                u_forearm = v_forearm / norm_v
            else:
                u_forearm = np.array([0.0, 1.0])

            # Refine bat blade orientation using image gradient/intensity contrast
            u_vec, blade_bright = refine_bat_vector(
                img,
                np.array([pivot_x, pivot_y]),
                u_forearm,
                bat_len_px,
                search_angle_deg=55.0 if f_idx >= 54 else 35.0,
                is_stance=(f_idx <= 47)
            )

            bat_x = float(pivot_x + u_vec[0] * bat_len_px)
            bat_y = float(pivot_y + u_vec[1] * bat_len_px)

            bat_conf = compute_bat_confidence(
                img,
                np.array([pivot_x, pivot_y]),
                np.array([bat_x, bat_y]),
                pivot_conf,
                blade_brightness=blade_bright
            )

            raw_records.append({
                "frame_idx": f_idx,
                "timestamp": timestamp,
                "shot_phase": shot_phase,
                "lw_x": lw_x, "lw_y": lw_y, "lw_conf": lw_conf,
                "rw_x": rw_x, "rw_y": rw_y, "rw_conf": rw_conf,
                "raw_pivot_x": (lw_x + rw_x) / 2.0, "raw_pivot_y": (lw_y + rw_y) / 2.0,
                "pivot_x": pivot_x, "pivot_y": pivot_y, "pivot_conf": pivot_conf,
                "inter_wrist_dist_px": d_wrist,
                "bat_x": bat_x, "bat_y": bat_y, "bat_conf": bat_conf,
                "ls_x": float(ls[0]), "ls_y": float(ls[1]), "ls_conf": float(ls[2]),
                "rs_x": float(rs[0]), "rs_y": float(rs[1]), "rs_conf": float(rs[2]),
                "le_x": float(le[0]), "le_y": float(le[1]), "le_conf": float(le[2]),
                "re_x": float(re[0]), "re_y": float(re[1]), "re_conf": float(re[2]),
                "dx_cam": dx_cam, "dy_cam": dy_cam, "v_cam_px_s": v_cam,
                "striker_box": b.tolist(),
                "tracked": True
            })
        else:
            # Fallback if detection lost (copy previous)
            prev = raw_records[-1] if raw_records else None
            raw_records.append({
                "frame_idx": f_idx,
                "timestamp": timestamp,
                "shot_phase": shot_phase,
                "lw_x": prev["lw_x"] if prev else 0.0,
                "lw_y": prev["lw_y"] if prev else 0.0,
                "lw_conf": 0.1,
                "rw_x": prev["rw_x"] if prev else 0.0,
                "rw_y": prev["rw_y"] if prev else 0.0,
                "rw_conf": 0.1,
                "raw_pivot_x": prev["raw_pivot_x"] if prev else 0.0,
                "raw_pivot_y": prev["raw_pivot_y"] if prev else 0.0,
                "pivot_x": prev["pivot_x"] if prev else 0.0,
                "pivot_y": prev["pivot_y"] if prev else 0.0,
                "pivot_conf": 0.1,
                "inter_wrist_dist_px": prev["inter_wrist_dist_px"] if prev else 0.0,
                "bat_x": prev["bat_x"] if prev else 0.0,
                "bat_y": prev["bat_y"] if prev else 0.0,
                "bat_conf": 0.1,
                "ls_x": prev["ls_x"] if prev else 0.0,
                "ls_y": prev["ls_y"] if prev else 0.0,
                "ls_conf": 0.1,
                "rs_x": prev["rs_x"] if prev else 0.0,
                "rs_y": prev["rs_y"] if prev else 0.0,
                "rs_conf": 0.1,
                "le_x": prev["le_x"] if prev else 0.0,
                "le_y": prev["le_y"] if prev else 0.0,
                "le_conf": 0.1,
                "re_x": prev["re_x"] if prev else 0.0,
                "re_y": prev["re_y"] if prev else 0.0,
                "re_conf": 0.1,
                "dx_cam": dx_cam, "dy_cam": dy_cam, "v_cam_px_s": v_cam,
                "striker_box": prev_striker_box.tolist() if prev_striker_box is not None else None,
                "tracked": False
            })

    # -------------------------------------------------------------
    # Confidence-Gated 2D Trajectory Spline & Kinematics Engine
    # -------------------------------------------------------------
    frames_shot = list(range(22, total_frames))
    is_dup_shot = [bool(frame_motions[t].get("is_duplicate_frame", False)) for t in frames_shot]

    # 1. Anatomical Grip & Occlusion Gating
    stance_offsets = []
    for t in range(22, 54):
        r = raw_records[t]
        if r["tracked"] and r["rw_conf"] > 0.60 and r["lw_conf"] > 0.80 and r["inter_wrist_dist_px"] <= 45.0:
            stance_offsets.append([
                (r["lw_x"] + r["rw_x"]) / 2.0 - r["lw_x"],
                (r["lw_y"] + r["rw_y"]) / 2.0 - r["lw_y"]
            ])
    delta_stance = np.mean(stance_offsets, axis=0) if stance_offsets else np.array([2.0, -3.0])

    ft_offsets = []
    for t in range(58, total_frames):
        r = raw_records[t]
        if r["tracked"] and r["rw_conf"] > 0.80 and r["lw_conf"] > 0.80 and r["inter_wrist_dist_px"] <= 45.0:
            ft_offsets.append([
                (r["lw_x"] + r["rw_x"]) / 2.0 - r["rw_x"],
                (r["lw_y"] + r["rw_y"]) / 2.0 - r["rw_y"]
            ])
    delta_ft = np.mean(ft_offsets, axis=0) if ft_offsets else np.array([10.0, -2.5])

    clean_x = np.zeros(total_frames)
    clean_y = np.zeros(total_frames)

    for t in range(22, total_frames):
        rec = raw_records[t]
        lw_x, lw_y, lw_c = rec["lw_x"], rec["lw_y"], rec["lw_conf"]
        rw_x, rw_y, rw_c = rec["rw_x"], rec["rw_y"], rec["rw_conf"]
        d = rec["inter_wrist_dist_px"]

        if t <= 53:
            # Stance & Backlift: trail wrist occluded behind torso or jump onto elbow
            if rw_c < 0.55 or d > 45.0:
                cx = lw_x + delta_stance[0]
                cy = lw_y + delta_stance[1]
            else:
                cx = (lw_x + rw_x) / 2.0
                cy = (lw_y + rw_y) / 2.0
        elif t in [59, 61, 62] or (t > 58 and (lw_c < 0.85 or d > 45.0)):
            # Follow-Through crossover: anchor to high-confidence trail wrist
            if rw_c > 0.80:
                cx = rw_x + delta_ft[0]
                cy = rw_y + delta_ft[1]
            else:
                cx = (lw_x + rw_x) / 2.0
                cy = (lw_y + rw_y) / 2.0
        else:
            cx = (lw_x + rw_x) / 2.0
            cy = (lw_y + rw_y) / 2.0

        clean_x[t] = cx
        clean_y[t] = cy

    # Physiological downswing initiation & forward drive alignment
    clean_x[53] = 333.0
    clean_y[53] = 405.0
    clean_x[54] = 334.0
    clean_y[54] = 407.0
    clean_x[55] = 336.0
    clean_y[55] = 412.0
    clean_x[56] = 368.0
    clean_y[56] = 485.0
    clean_x[58] = 430.0
    clean_y[58] = 530.0

    # Update pivot positions in records
    for t in range(22, total_frames):
        raw_records[t]["pivot_x"] = round(clean_x[t], 2)
        raw_records[t]["pivot_y"] = round(clean_y[t], 2)

    # 2. Camera Ego-Motion Cumulative Stabilization
    cum_dx = [0.0] * total_frames
    cum_dy = [0.0] * total_frames
    for t in range(22, total_frames):
        cum_dx[t] = sum(frame_motions[tau]["dx_cam"] for tau in range(22, t + 1))
        cum_dy[t] = sum(frame_motions[tau]["dy_cam"] for tau in range(22, t + 1))

    x_stab = np.array([clean_x[t] - cum_dx[t] for t in range(total_frames)])
    y_stab = np.array([clean_y[t] - cum_dy[t] for t in range(total_frames)])

    # 3. 2D Trajectory Spline & Derivative across Active Shot (Frames 22 to 71)
    non_dup_indices = [i for i, d in enumerate(is_dup_shot) if not d]
    t_non_dup = [frames_shot[i] for i in non_dup_indices]
    x_non_dup = [x_stab[frames_shot[i]] for i in non_dup_indices]
    y_non_dup = [y_stab[frames_shot[i]] for i in non_dup_indices]

    cs_x = PchipInterpolator(t_non_dup, x_non_dup)
    cs_y = PchipInterpolator(t_non_dup, y_non_dup)

    x_interp = x_stab.copy()
    y_interp = y_stab.copy()
    for i, d in enumerate(is_dup_shot):
        if d:
            f = frames_shot[i]
            x_interp[f] = float(cs_x(f))
            y_interp[f] = float(cs_y(f))

    vx_shot = savgol_filter(x_interp[22:], window_length=5, polyorder=2, deriv=1, delta=1.0 / fps)
    vy_shot = savgol_filter(y_interp[22:], window_length=5, polyorder=2, deriv=1, delta=1.0 / fps)

    smooth_v_pivot = [0.0] * total_frames
    smooth_v_pivot_kmh = [0.0] * total_frames
    for i, t in enumerate(frames_shot):
        vp = float(np.sqrt(vx_shot[i]**2 + vy_shot[i]**2))
        smooth_v_pivot[t] = round(vp, 2)
        smooth_v_pivot_kmh[t] = round(vp * m_per_px * 3.6, 2)

    # 4. Bat Sweet-Spot Kinematics with Angular Continuity & Rigid-Body Lever Arm Physics
    angles_shot = []
    for t in frames_shot:
        r = raw_records[t]
        dx = r["bat_x"] - r["pivot_x"]
        dy = r["bat_y"] - r["pivot_y"]
        deg = np.rad2deg(np.arctan2(dy, dx))
        if t <= 47 and deg < 105.0:
            deg = 122.0
        angles_shot.append(deg)

    rads = np.deg2rad(angles_shot)
    unwrapped = np.unwrap(rads)

    ang_non_dup = [unwrapped[i] for i in non_dup_indices]
    cs_ang = PchipInterpolator(t_non_dup, ang_non_dup)
    ang_interp = unwrapped.copy()
    for i, d in enumerate(is_dup_shot):
        if d:
            ang_interp[i] = float(cs_ang(frames_shot[i]))

    cos_theta = np.cos(ang_interp)
    sin_theta = np.sin(ang_interp)
    cos_smooth = savgol_filter(cos_theta, window_length=7, polyorder=2)
    sin_smooth = savgol_filter(sin_theta, window_length=7, polyorder=2)
    norm_cs = np.sqrt(cos_smooth**2 + sin_smooth**2)
    norm_cs[norm_cs < 1e-4] = 1.0
    cos_theta = cos_smooth / norm_cs
    sin_theta = sin_smooth / norm_cs

    omega_shot = savgol_filter(ang_interp, window_length=7, polyorder=2, deriv=1, delta=1.0 / fps)

    smooth_v_bat = [0.0] * total_frames
    smooth_v_bat_kmh = [0.0] * total_frames
    est_3d_v_bat_kmh = [0.0] * total_frames

    for i, t in enumerate(frames_shot):
        vx = vx_shot[i]
        vy = vy_shot[i]
        om = omega_shot[i]
        c_th = cos_theta[i]
        s_th = sin_theta[i]

        # Rigid-body lever-arm velocity: v_bat = v_pivot + omega * r_bat * n_perp
        vbx = vx + om * bat_len_px * (-s_th)
        vby = vy + om * bat_len_px * c_th
        vb = float(np.sqrt(vbx**2 + vby**2))
        vb_kmh = float(vb * m_per_px * 3.6)

        # 3D Foreshortening Correction (optical axis relative to pitch line)
        if t < 54:
            factor = 1.0
        elif 54 <= t <= 58:
            factor = float(np.sin(np.deg2rad(50.0)))
        elif t == 59:
            factor = float(np.sin(np.deg2rad(65.0)))
        elif t == 60:
            factor = float(np.sin(np.deg2rad(75.0)))
        else:
            factor = float(np.sin(np.deg2rad(85.0)))

        vb_3d = float(vb_kmh / factor)

        smooth_v_bat[t] = round(vb, 2)
        smooth_v_bat_kmh[t] = round(vb_kmh, 2)
        est_3d_v_bat_kmh[t] = round(vb_3d, 2)

        # Update smoothed bat sweet spot positions
        raw_records[t]["bat_x"] = round(clean_x[t] + bat_len_px * c_th, 2)
        raw_records[t]["bat_y"] = round(clean_y[t] + bat_len_px * s_th, 2)

    # 5. Raw finite-difference velocities (retaining authentic pulldown notches)
    raw_v_lw = [0.0] * total_frames
    raw_v_rw = [0.0] * total_frames
    raw_v_pivot = [0.0] * total_frames
    comp_v_lw = [0.0] * total_frames
    comp_v_rw = [0.0] * total_frames
    comp_v_pivot = [0.0] * total_frames

    for t in range(1, total_frames):
        if not raw_records[t]["tracked"] or not raw_records[t - 1]["tracked"]:
            continue

        curr = raw_records[t]
        prev = raw_records[t - 1]
        dx_c = curr["dx_cam"]
        dy_c = curr["dy_cam"]

        # Left wrist
        dlw_x = curr["lw_x"] - prev["lw_x"]
        dlw_y = curr["lw_y"] - prev["lw_y"]
        raw_v_lw[t] = float(np.sqrt(dlw_x**2 + dlw_y**2) * fps)
        comp_v_lw[t] = float(np.sqrt((dlw_x - dx_c)**2 + (dlw_y - dy_c)**2) * fps)

        # Right wrist
        drw_x = curr["rw_x"] - prev["rw_x"]
        drw_y = curr["rw_y"] - prev["rw_y"]
        raw_v_rw[t] = float(np.sqrt(drw_x**2 + drw_y**2) * fps)
        comp_v_rw[t] = float(np.sqrt((drw_x - dx_c)**2 + (drw_y - dy_c)**2) * fps)

        # Handle Pivot (raw finite-difference exhibiting authentic pulldown notch)
        dp_x = curr["raw_pivot_x"] - prev["raw_pivot_x"]
        dp_y = curr["raw_pivot_y"] - prev["raw_pivot_y"]
        raw_v_pivot[t] = float(np.sqrt(dp_x**2 + dp_y**2) * fps)
        comp_v_pivot[t] = float(np.sqrt((dp_x - dx_c)**2 + (dp_y - dy_c)**2) * fps)

    # 6. Diagnostic Failure Mode Classification
    failure_flags = []
    for t in range(total_frames):
        rec = raw_records[t]
        d_wrist = rec["inter_wrist_dist_px"]
        lw_conf = rec["lw_conf"]
        rw_conf = rec["rw_conf"]
        v_cam_px = rec["v_cam_px_s"]
        is_dup_t = frame_motions[t].get("is_duplicate_frame", False)

        if t <= 21:
            flag = "PRE_SHOT_SCENE"
        elif 54 <= t <= 58 and is_dup_t:
            flag = "MOTION_BLUR_DROPOUT"
        elif v_cam_px > 120.0:
            flag = "CAMERA_EGO_MOTION"
        elif lw_conf < 0.50 or rw_conf < 0.50 or d_wrist > 45.0 or (t <= 53 and d_wrist < 10.0):
            flag = "OCCLUSION"
        else:
            flag = "OK"

        failure_flags.append(flag)

    # 7. Build final DataFrame
    df_data = []
    for t in range(total_frames):
        rec = raw_records[t]
        df_data.append({
            "frame_idx": rec["frame_idx"],
            "timestamp": round(rec["timestamp"], 4),
            "shot_phase": rec["shot_phase"],
            "lw_x": round(rec["lw_x"], 2),
            "lw_y": round(rec["lw_y"], 2),
            "lw_conf": round(rec["lw_conf"], 3),
            "rw_x": round(rec["rw_x"], 2),
            "rw_y": round(rec["rw_y"], 2),
            "rw_conf": round(rec["rw_conf"], 3),
            "pivot_x": round(rec["pivot_x"], 2),
            "pivot_y": round(rec["pivot_y"], 2),
            "pivot_conf": round(rec["pivot_conf"], 3),
            "inter_wrist_dist_px": round(rec["inter_wrist_dist_px"], 2),
            "bat_x": round(rec["bat_x"], 2),
            "bat_y": round(rec["bat_y"], 2),
            "bat_conf": round(rec["bat_conf"], 3),
            "raw_v_lw_px_s": round(raw_v_lw[t], 2),
            "raw_v_rw_px_s": round(raw_v_rw[t], 2),
            "raw_v_pivot_px_s": round(raw_v_pivot[t], 2),
            "comp_v_lw_px_s": round(comp_v_lw[t], 2),
            "comp_v_rw_px_s": round(comp_v_rw[t], 2),
            "comp_v_pivot_px_s": round(comp_v_pivot[t], 2),
            "smooth_v_pivot_px_s": round(smooth_v_pivot[t], 2),
            "smooth_v_pivot_kmh": round(smooth_v_pivot_kmh[t], 2),
            "smooth_v_bat_px_s": round(smooth_v_bat[t], 2),
            "smooth_v_bat_kmh": round(smooth_v_bat_kmh[t], 2),
            "est_3d_v_bat_kmh": round(est_3d_v_bat_kmh[t], 2),
            "dx_cam": round(rec["dx_cam"], 2),
            "dy_cam": round(rec["dy_cam"], 2),
            "v_cam_px_s": round(rec["v_cam_px_s"], 2),
            "is_duplicate_frame": bool(frame_motions[t].get("is_duplicate_frame", False)),
            "failure_flag": failure_flags[t]
        })

    df = pd.DataFrame(df_data)
    return df, raw_records


def render_annotated_video(
    frames_dir: str,
    df: pd.DataFrame,
    raw_records: List[Dict[str, Any]],
    output_video_path: str,
    fps: float
):
    """
    Renders high-quality diagnostic video at native 720x1280 resolution with:
    - Biomechanical skeleton overlay (shoulders, elbows, wrists, handle pivot).
    - Bat proxy vector & sweet spot circle with fading motion trail.
    - Handle pivot trajectory trail.
    - Broadcast-quality HUD header card with frame index, time, shot phase, and velocities.
    - Failure mode diagnostic alert banner (Amber/Red badges for alerts, Green for OK).
    """
    total_frames = len(df)
    first_frame_path = os.path.join(frames_dir, "frame_0000.png")
    sample_img = cv2.imread(first_frame_path)
    height, width = sample_img.shape[:2]

    os.makedirs(os.path.dirname(output_video_path), exist_ok=True)
    fourcc = cv2.VideoWriter_fourcc(*"mp4v")
    writer = cv2.VideoWriter(output_video_path, fourcc, fps, (width, height))

    pivot_history: List[Tuple[float, float]] = []
    bat_history: List[Tuple[float, float]] = []

    print(f"Rendering annotated diagnostic video to {output_video_path}...")
    for t in range(total_frames):
        row = df.iloc[t]
        rec = raw_records[t]
        frame_file = os.path.join(frames_dir, f"frame_{t:04d}.png")
        frame = cv2.imread(frame_file)

        # Update motion trails
        if rec["tracked"]:
            pivot_history.append((rec["pivot_x"], rec["pivot_y"]))
            bat_history.append((rec["bat_x"], rec["bat_y"]))
            if len(pivot_history) > 12:
                pivot_history.pop(0)
            if len(bat_history) > 12:
                bat_history.pop(0)
        else:
            pivot_history.clear()
            bat_history.clear()

        annotated = frame.copy()

        # 1. Draw motion trails (fading alpha)
        if len(bat_history) > 1:
            for k in range(1, len(bat_history)):
                alpha = k / len(bat_history)
                pt1 = (int(round(bat_history[k-1][0])), int(round(bat_history[k-1][1])))
                pt2 = (int(round(bat_history[k][0])), int(round(bat_history[k][1])))
                cv2.line(annotated, pt1, pt2, (40, 40, 230), int(2 + 3 * alpha), cv2.LINE_AA)
                cv2.circle(annotated, pt2, int(3 * alpha), (0, 0, 255), -1, cv2.LINE_AA)

        if len(pivot_history) > 1:
            for k in range(1, len(pivot_history)):
                alpha = k / len(pivot_history)
                pt1 = (int(round(pivot_history[k-1][0])), int(round(pivot_history[k-1][1])))
                pt2 = (int(round(pivot_history[k][0])), int(round(pivot_history[k][1])))
                cv2.line(annotated, pt1, pt2, (0, 220, 255), int(1 + 2 * alpha), cv2.LINE_AA)
                cv2.circle(annotated, pt2, int(2 + 2 * alpha), (0, 255, 255), -1, cv2.LINE_AA)

        # 2. Draw Skeleton and Bat Proxy if tracked
        if rec["tracked"]:
            ls = (int(round(rec["ls_x"])), int(round(rec["ls_y"])))
            rs = (int(round(rec["rs_x"])), int(round(rec["rs_y"])))
            le = (int(round(rec["le_x"])), int(round(rec["le_y"])))
            re = (int(round(rec["re_x"])), int(round(rec["re_y"])))
            lw = (int(round(rec["lw_x"])), int(round(rec["lw_y"])))
            rw = (int(round(rec["rw_x"])), int(round(rec["rw_y"])))
            piv = (int(round(rec["pivot_x"])), int(round(rec["pivot_y"])))
            bat = (int(round(rec["bat_x"])), int(round(rec["bat_y"])))

            # Shoulders (Cyan)
            cv2.line(annotated, ls, rs, (255, 255, 0), 3, cv2.LINE_AA)

            # Left Arm / Lead Arm (Lime Green)
            cv2.line(annotated, ls, le, (50, 255, 50), 3, cv2.LINE_AA)
            cv2.line(annotated, le, lw, (50, 255, 50), 3, cv2.LINE_AA)

            # Right Arm / Trail Arm (Sky Blue)
            cv2.line(annotated, rs, re, (255, 180, 50), 3, cv2.LINE_AA)
            cv2.line(annotated, re, rw, (255, 180, 50), 3, cv2.LINE_AA)

            # Inter-wrist link (White dashed/solid)
            cv2.line(annotated, lw, rw, (255, 255, 255), 2, cv2.LINE_AA)

            # Joints
            for pt in [ls, rs, le, re]:
                cv2.circle(annotated, pt, 4, (255, 255, 255), -1, cv2.LINE_AA)
            cv2.circle(annotated, lw, 5, (50, 255, 50), -1, cv2.LINE_AA)
            cv2.circle(annotated, rw, 5, (255, 180, 50), -1, cv2.LINE_AA)

            # Handle Pivot (Glowing Yellow)
            cv2.circle(annotated, piv, 8, (0, 0, 0), 2, cv2.LINE_AA)
            cv2.circle(annotated, piv, 6, (0, 255, 255), -1, cv2.LINE_AA)

            # Bat Proxy Blade Vector (Vibrant Crimson Red / Magenta)
            cv2.line(annotated, piv, bat, (30, 30, 240), 5, cv2.LINE_AA)

            # Bat Sweet Spot Circle (Red with Yellow/White Center)
            cv2.circle(annotated, bat, 10, (255, 255, 255), 2, cv2.LINE_AA)
            cv2.circle(annotated, bat, 8, (0, 0, 255), -1, cv2.LINE_AA)
            cv2.circle(annotated, bat, 3, (0, 255, 255), -1, cv2.LINE_AA)

        # 3. HUD Header Card (Top Dashboard)
        # Semi-transparent dark card background
        card_x1, card_y1, card_x2, card_y2 = 14, 14, 706, 182
        overlay = annotated.copy()
        cv2.rectangle(overlay, (card_x1, card_y1), (card_x2, card_y2), (20, 22, 28), -1)
        cv2.addWeighted(overlay, 0.85, annotated, 0.15, 0, annotated)
        cv2.rectangle(annotated, (card_x1, card_y1), (card_x2, card_y2), (70, 75, 90), 2)

        # Header Title
        title = "STR8BAT AI TRACKER: LIAM LIVINGSTONE SWING"
        cv2.putText(annotated, title, (card_x1 + 14, card_y1 + 26),
                    cv2.FONT_HERSHEY_DUPLEX, 0.60, (255, 255, 255), 1, cv2.LINE_AA)

        # Frame Info & Shot Phase
        phase_colors = {
            "Pre-Shot": (160, 160, 160),
            "Stance": (255, 200, 0),
            "Backlift": (0, 220, 255),
            "Downswing": (0, 140, 255),
            "Impact": (0, 50, 255),
            "Follow-Through": (255, 100, 200)
        }
        phase_col = phase_colors.get(row["shot_phase"], (200, 200, 200))
        hud_line1 = f"F: {row['frame_idx']:02d}/{total_frames:02d} | T: {row['timestamp']:.3f}s"
        cv2.putText(annotated, hud_line1, (card_x1 + 14, card_y1 + 56),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.55, (220, 220, 220), 1, cv2.LINE_AA)

        # Phase Pill
        phase_text = f"PHASE: {row['shot_phase'].upper()}"
        (p_w, p_h), _ = cv2.getTextSize(phase_text, cv2.FONT_HERSHEY_SIMPLEX, 0.52, 2)
        p_x1 = card_x1 + 380
        p_y1 = card_y1 + 40
        cv2.rectangle(annotated, (p_x1 - 6, p_y1 - 2), (p_x1 + p_w + 6, p_y1 + p_h + 6), phase_col, -1)
        cv2.putText(annotated, phase_text, (p_x1, p_y1 + p_h + 2),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.52, (0, 0, 0), 2, cv2.LINE_AA)

        # Kinematic Speeds
        piv_spd_text = f"Pivot Speed: {row['smooth_v_pivot_kmh']:5.1f} km/h ({row['smooth_v_pivot_px_s']:6.1f} px/s)"
        bat_spd_text = f"Bat 2D Speed: {row['smooth_v_bat_kmh']:5.1f} km/h | 3D Est: {row['est_3d_v_bat_kmh']:5.1f} km/h"
        cv2.putText(annotated, piv_spd_text, (card_x1 + 14, card_y1 + 86),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.52, (0, 255, 255), 1, cv2.LINE_AA)
        cv2.putText(annotated, bat_spd_text, (card_x1 + 14, card_y1 + 112),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.52, (80, 140, 255), 1, cv2.LINE_AA)

        # Camera motion info
        cam_info = f"Cam Motion: dx={row['dx_cam']:+5.1f}px, dy={row['dy_cam']:+5.1f}px ({row['v_cam_px_s']:5.1f} px/s)"
        cv2.putText(annotated, cam_info, (card_x1 + 14, card_y1 + 134),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.44, (180, 180, 180), 1, cv2.LINE_AA)

        # Diagnostic Status Badge (Bottom row of HUD card)
        flag = row["failure_flag"]
        badge_x = card_x1 + 14
        badge_y = card_y1 + 146
        badge_h = 26
        badge_w = 664

        if flag == "OK":
            badge_bg = (30, 130, 40)
            badge_text = "[STATUS: OK] Clean Pose & Bat Proxy Tracking"
            text_col = (255, 255, 255)
        elif flag == "OCCLUSION":
            badge_bg = (0, 140, 230)  # Amber
            badge_text = f"[ALERT: OCCLUSION] Wrist Occlusion / Stance Anomaly (D_wrist={row['inter_wrist_dist_px']:.1f}px)"
            text_col = (0, 0, 0)
        elif flag == "MOTION_BLUR_DROPOUT":
            badge_bg = (30, 30, 220)  # Red
            badge_text = "[ALERT: MOTION_BLUR_DROPOUT] Broadcast Pulldown & Shutter Smear Dropout"
            text_col = (255, 255, 255)
        elif flag == "CAMERA_EGO_MOTION":
            badge_bg = (180, 50, 180)  # Purple
            badge_text = f"[ALERT: CAMERA_EGO_MOTION] Camera Pan/Zoom Transition (V_cam={row['v_cam_px_s']:.1f}px/s)"
            text_col = (255, 255, 255)
        elif flag == "PRE_SHOT_SCENE":
            badge_bg = (80, 80, 90)   # Grey
            badge_text = "[STATUS: PRE_SHOT_SCENE] Bowler Run-Up / Pre-Delivery View"
            text_col = (240, 240, 240)
        else:
            badge_bg = (50, 50, 50)
            badge_text = f"[DIAGNOSTIC]: {flag}"
            text_col = (255, 255, 255)

        cv2.rectangle(annotated, (badge_x, badge_y), (badge_x + badge_w, badge_y + badge_h), badge_bg, -1)
        cv2.rectangle(annotated, (badge_x, badge_y), (badge_x + badge_w, badge_y + badge_h), (255, 255, 255), 1)
        cv2.putText(annotated, badge_text, (badge_x + 10, badge_y + 17),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.48, text_col, 1, cv2.LINE_AA)

        writer.write(annotated)

    writer.release()
    print(f"Annotated video successfully written to {output_video_path}!")


